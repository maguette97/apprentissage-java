package apprentissage;

public class Signe {
    public static void main(String[] args) {
        int n = 0;

        if (n > 0) {
            System.out.println("Positif");
        } else if (n < 0) {
            System.out.println("Négatif");
        } else {
            System.out.println("Null");
        }
    }

}
